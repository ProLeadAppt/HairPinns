/**
 * Storefront products that are not in a public collection have no collection
 * grid to link them. The HTML sitemap lists those products so they stay
 * crawlable when they are published to the headless channel.
 */
export function productsMissingPublicCollection(products, isPublicCollection = () => false) {
  return products
    .filter((product) => {
      const collections = Array.isArray(product?.collections) ? product.collections : [];
      return Boolean(product?.handle) && !collections.some((handle) => isPublicCollection(handle));
    })
    .map((product) => ({
      handle: product.handle,
      title: product.title || product.handle,
    }))
    .sort((left, right) => left.title.localeCompare(right.title) || left.handle.localeCompare(right.handle));
}

export function renderUncategorisedProductsModule(products) {
  return `// Generated by scripts/generate-sitemap.js. Do not edit.
export const UNCATEGORISED_PRODUCTS = ${JSON.stringify(products, null, 2)};
`;
}
